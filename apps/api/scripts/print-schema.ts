import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { printSchema } from 'graphql'
import { schema } from '../src/schema'

const target = fileURLToPath(new URL('../../../packages/graphql/schema.graphql', import.meta.url))
writeFileSync(target, `# Generated by apps/api/scripts/print-schema.ts — do not edit.\n\n${printSchema(schema)}\n`)
console.log(`✔ wrote ${target}`)
