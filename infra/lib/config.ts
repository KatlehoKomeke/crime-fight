export type StageName = 'qa' | 'prod'

/**
 * Federated sign-in (the only way in). A provider is enabled once its public
 * IDs are set; its secrets live in one Secrets Manager secret (`secretName`)
 * as JSON: `{ "googleClientSecret": "...", "applePrivateKey": "-----BEGIN PRIVATE KEY-----..." }`.
 * One Google OAuth client and one Apple Services ID can serve both stages.
 */
export interface SsoConfig {
  google?: { clientId: string }
  apple?: { servicesId: string; teamId: string; keyId: string }
  secretName: string
}

export interface StageConfig {
  stage: StageName
  account: string | undefined
  region: string
  /** Optional custom domain. Requires `certificateArn` (us-east-1, for CloudFront). */
  domainName?: string
  certificateArn?: string
  hostedZoneId?: string
  hostedZoneName?: string
  database: {
    /** 0 lets Aurora Serverless v2 pause when idle (resume takes ~15s). */
    minCapacity: number
    maxCapacity: number
    readers: number
    deletionProtection: boolean
    backupRetentionDays: number
  }
  api: { memoryMb: number; reservedConcurrency?: number; throttleRate: number; throttleBurst: number }
  web: { memoryMb: number }
  /** Only allow operations generated by codegen (persisted queries). */
  persistedOnly: boolean
  alarmEmail?: string
  /** Extra Cognito callback URLs, e.g. localhost for testing QA auth from a laptop. */
  extraCallbackUrls: string[]
  sso: SsoConfig
  /**
   * Request the busiest pages through CloudFront every minute, keeping edge
   * copies fresh and the SSR and GraphQL Lambdas warm. Off where the database
   * should be allowed to pause, because the requests would keep it awake.
   */
  warm: boolean
  /**
   * Bounty money. `paystack` once a Secrets Manager secret (`secretName`, JSON
   * `{"secretKey": "sk_...", "fingerprintKey": "<random, never rotated>"}`)
   * exists for the stage; until then `disabled`, which lists bounties read-only.
   * See docs/adr/0006-bounties.md for what must be true before live keys.
   */
  payments: { provider: 'disabled' | 'paystack'; secretName?: string; sweep: boolean }
  /** Handles who review bounties and release money. Never handed out by sign-in. */
  adminHandles: string[]
}

const env = process.env
const optionalNumber = (value: string | undefined) => (value ? Number(value) : undefined)
const handles = (value: string | undefined) => (value ?? '').split(',').map((h) => h.trim().replace(/^@/, '').toLowerCase()).filter(Boolean)
// The hourly sweep only has work once payments are on; without them it would just keep Aurora awake.
const payments = (secretName: string | undefined, sweep: boolean): StageConfig['payments'] => (secretName ? { provider: 'paystack', secretName, sweep } : { provider: 'disabled', sweep: false })

const sso: SsoConfig = {
  google: env.GOOGLE_CLIENT_ID ? { clientId: env.GOOGLE_CLIENT_ID } : undefined,
  apple:
    env.APPLE_SERVICES_ID && env.APPLE_TEAM_ID && env.APPLE_KEY_ID
      ? { servicesId: env.APPLE_SERVICES_ID, teamId: env.APPLE_TEAM_ID, keyId: env.APPLE_KEY_ID }
      : undefined,
  secretName: env.SSO_SECRET_NAME ?? 'civic/sso',
}

/**
 * QA and prod can live in the same account or separate ones; set
 * QA_AWS_ACCOUNT_ID / PROD_AWS_ACCOUNT_ID (GitHub environment variables) to split.
 */
export const stages: Record<StageName, StageConfig> = {
  qa: {
    stage: 'qa',
    account: env.QA_AWS_ACCOUNT_ID ?? env.CDK_DEFAULT_ACCOUNT,
    region: env.QA_AWS_REGION ?? env.CDK_DEFAULT_REGION ?? 'af-south-1',
    domainName: env.QA_DOMAIN_NAME,
    certificateArn: env.QA_CERTIFICATE_ARN,
    hostedZoneId: env.QA_HOSTED_ZONE_ID,
    hostedZoneName: env.QA_HOSTED_ZONE_NAME,
    database: { minCapacity: 0, maxCapacity: 2, readers: 0, deletionProtection: false, backupRetentionDays: 1 },
    api: { memoryMb: 1024, throttleRate: 50, throttleBurst: 100 },
    web: { memoryMb: 1536 },
    persistedOnly: false,
    alarmEmail: env.QA_ALARM_EMAIL,
    extraCallbackUrls: ['http://localhost:8081/auth/callback'],
    sso,
    warm: false,
    // No hourly sweep on QA: it would keep Aurora awake.
    payments: payments(env.QA_PAYSTACK_SECRET_NAME, false),
    adminHandles: handles(env.QA_ADMIN_HANDLES ?? env.ADMIN_HANDLES),
  },
  prod: {
    stage: 'prod',
    account: env.PROD_AWS_ACCOUNT_ID ?? env.CDK_DEFAULT_ACCOUNT,
    region: env.PROD_AWS_REGION ?? env.CDK_DEFAULT_REGION ?? 'af-south-1',
    domainName: env.PROD_DOMAIN_NAME,
    certificateArn: env.PROD_CERTIFICATE_ARN,
    hostedZoneId: env.PROD_HOSTED_ZONE_ID,
    hostedZoneName: env.PROD_HOSTED_ZONE_NAME,
    // Pre-launch traffic: one instance that pauses after 15 idle minutes (storage is all that's billed while paused). The first
    // request after a pause waits ~15 s while it resumes; the API retries through it. Add readers and a non-zero minimum at launch.
    database: { minCapacity: 0, maxCapacity: 4, readers: 0, deletionProtection: true, backupRetentionDays: 14 },
    // Reserving needs an account concurrency quota of reserved + 100; new accounts start at 10.
    api: { memoryMb: 1536, reservedConcurrency: optionalNumber(env.PROD_API_RESERVED_CONCURRENCY), throttleRate: 500, throttleBurst: 1000 },
    web: { memoryMb: 2048 },
    persistedOnly: true,
    alarmEmail: env.PROD_ALARM_EMAIL,
    extraCallbackUrls: [],
    sso,
    // The warmer loads pages every minute, and every page queries the database, so it would keep Aurora from ever pausing.
    warm: false,
    payments: payments(env.PROD_PAYSTACK_SECRET_NAME, true),
    adminHandles: handles(env.PROD_ADMIN_HANDLES ?? env.ADMIN_HANDLES),
  },
}

/** Native deep-link scheme per stage; must match apps/app/app.config.ts. */
export const appScheme = (stage: StageName) => (stage === 'prod' ? 'civicone' : `civicone-${stage}`)
